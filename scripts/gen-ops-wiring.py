#!/usr/bin/env python3
"""Generate the cluster wiring from its two declarations.   `just ops-wiring`

    python3 scripts/gen-ops-wiring.py            write the generated files
    python3 scripts/gen-ops-wiring.py --check    exit 1 (with a diff) if any is stale
    python3 scripts/gen-ops-wiring.py --out DIR  write them under DIR instead

Two accounts reach the cluster from this box and each has ONE hand-written
declaration of what it may do; everything else is rendered from it. The second
account joined this script on 2026-09-23 rather than getting a generator of its
own: a Role and its can-i proof are the same problem twice, and one `--check` in
CI (ci.yml) covering both is what stops either drifting from review.

    apps/bothy-ops/catalog.toml       bothy-ops - what a browser may do to the cluster
    apps/bothy-collector/reads.toml   bothy-collector - what the portal's 30 s timer reads

The catalog is the only hand-written description of what the cluster tier may
do. Before 2026-09 the same ids were copied by hand into four places and a
check asserted the copies agreed; every new action was four edits and one
chance to get the Role wrong. Now the copies are OUTPUTS:

  edge/dynamic/bothy-ops.yml                  one exact Path() router per action
                                              (sso-viewer for a read, sso-operator
                                              for a change), the catalog route,
                                              and the three container verbs
  k8s/rbac/bothy-kube.yaml                    the Role in each of guard.NAMESPACES,
                                              merged from every action's `rbac`
  scripts/lib/bothy-kube-probes.sh            the can-i rows `just kube-token` prints:
                                              every granted verb must be yes, and
                                              the forbidden list must be no
  apps/bothy-web/web/src/lib/kube-catalog.dev.json
                                              what GET /-/api/kube/catalog serves,
                                              for `vite dev` and the web checks

and, from reads.toml:

  k8s/rbac/bothy-collector.yaml               the ServiceAccount, the list-only
                                              ClusterRole and its binding
  scripts/lib/bothy-collector-probes.sh       the can-i rows `just collector-token`
                                              prints - every granted list, then
                                              the refusals

guard.load_catalog validates the catalog first - including the rbac rules
(no secrets, exec, attach, portforward, watch, escalate, bind, impersonate;
create only on jobs; delete only on pods and jobs) - so a catalog that would
generate a dangerous Role never generates anything. load_reads() does the same
for reads.toml, where the rule is stricter still: every row is a `list`, the
verb is not even spellable in the file, and `secrets` is refused by name.

Stdlib plus tomllib. The YAML is written as text, not dumped: the edge file is
rendered by Traefik as a Go template, where a doubled curly brace anywhere
(comments included) voids the whole file, so every byte here is chosen.
"""

