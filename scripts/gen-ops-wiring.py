def _can_i_resource(grp: str, res: str) -> str:
    """`deployments.apps --scale`: the probe passes the part after `--` as
    --subresource. NOT `deployments.apps/scale` - `kubectl auth can-i` reads
    TYPE/NAME there, so that spelling asks about a deployment NAMED scale, and
    `get pods/exec` quietly answers `get pods` (found 2026-09-17: it said yes)."""
    base, _, sub = res.partition("/")
    full = f"{base}.{grp}" if grp else base
    return f"{full} --{sub}" if sub else full


def _row(expect: str, verb: str, res: str, ns: str) -> str:
    base, _, sub = res.partition(" --")
    return f"probe {expect} {verb} {base} {ns}" + (f" --{sub}" if sub else "")


def gen_probes(cat: guard.Catalog) -> str:
    rows = ["# shellcheck shell=bash",
            f"# {STAMP}",
            "#",
            "# Sourced by scripts/gen-kube-token.sh, which defines",
            "#   probe <expect yes|no> <verb> <resource[/name]> <namespace or - for cluster scope> [--<subresource>]",
            "# `configmaps/thales` is a NAME (resourceNames). A subresource is never written",
            "# `pods/exec`: can-i reads that as a pod named exec, and answers for `get pods`.",
            "# Every verb the generated Role grants must be yes; the refusals must be no.",
            ""]
    for ns in guard.NAMESPACES:
        rows.append(f"# ── {ns}: granted ──")
        for grp, res, verbs, _ in merged_rules(cat):
            targets = ([f"{_can_i_resource(grp, res)}/{c}" for c in cat.policy.configmaps]
                       if res == "configmaps" else [_can_i_resource(grp, res)])
            for t in targets:
                for v in verbs:
                    rows.append(_row("yes", v, t, ns))
        rows.append(f"# ── {ns}: refused ──")
        for v, r, n in MUST_NOT:
            rows.append(_row("no", v, r, n.format(ns=ns)))
    rows.append("# ── outside the two namespaces, and cluster scope ──")
    for v, r, n in MUST_NOT_ANYWHERE:
        rows.append(_row("no", v, r, n))
    return "\n".join(rows) + "\n"


def gen_devjson(cat: guard.Catalog) -> str:
    return json.dumps(guard.catalog_json(cat), indent=2) + "\n"


# ── bothy-collector: the portal's 30-second cluster read ────────────────────
#
# Same shape as everything above - a declaration in, a Role and its can-i proof
# out - for the other account that touches the cluster from this box.

READ_KEYS = {"id", "resource", "group", "scope", "why"}
READ_SCOPES = ("cluster", "all-namespaces")
# Refused by name rather than left to review. `secrets` is the read that is a
# credential; the rest are the resources whose bodies carry more than a picture
# of what is deployed, and none of them appears in collect.py.
READS_DENY = {"secrets", "serviceaccounts", "roles", "rolebindings",
              "clusterroles", "clusterrolebindings", "nodes", "*"}


def load_reads(path: str | None = None) -> list[dict[str, str]]:
    """reads.toml -> the rows, validated. Raises rather than generating a Role
    nobody would sign off: no verb is spellable (every row is a `list`), no
    subresource, no wildcard, and the deny list above by name."""
    with open(path or os.path.join(ROOT, READS), "rb") as fh:
        raw = tomllib.load(fh)
    rows: list[dict[str, str]] = []
    seen: set[tuple[str, str]] = set()
    for i, r in enumerate(raw.get("read") or []):
        extra = set(r) - READ_KEYS
        if extra:
            # A `verbs = ["delete"]` here would otherwise sit in the file looking
            # effective while the generator ignored it - the worst kind of
            # security config, one that reads as a grant and is not one.
            raise ReadsError(f"read {i}: unknown key(s) {sorted(extra)}; only {sorted(READ_KEYS)} exist")
        missing = READ_KEYS - set(r)
        if missing:
            raise ReadsError(f"read {i}: missing {sorted(missing)}")
        if not all(isinstance(r[k], str) for k in READ_KEYS):
            raise ReadsError(f"read {i}: every value must be a string")
        if r["scope"] not in READ_SCOPES:
            raise ReadsError(f"read {r['id']}: scope must be one of {READ_SCOPES}")
        if "/" in r["resource"] or "*" in r["resource"] + r["group"]:
            raise ReadsError(f"read {r['id']}: no subresources and no wildcards")
        if r["resource"] in READS_DENY:
            raise ReadsError(f"read {r['id']}: `{r['resource']}` is refused here, whatever it is for")
        key = (r["group"], r["resource"])
        if key in seen:
            raise ReadsError(f"read {r['id']}: {key} is declared twice")
        seen.add(key)
        rows.append({k: r[k] for k in READ_KEYS})
    if not rows:
        raise ReadsError("no [[read]] rows - that would generate an empty ClusterRole")
    return sorted(rows, key=lambda r: (r["group"], r["resource"]))


def _can_i_target(row: dict[str, str]) -> str:
    return f"{row['resource']}.{row['group']}" if row["group"] else row["resource"]


COLL_RBAC_HEAD = """\
# {stamp}
#
# bothy-collector's identity in the cluster, and the whole of what it may do.
#
#   kubectl --context thales-scc apply -f k8s/rbac/bothy-collector.yaml
#   (just collector-token does it)
#
# The account the portal's discovery timer reads the cluster with, every 30
# seconds, from the host. Until 2026-09-23 there was no account: collect.py ran
# as devssh with ~/.kube/config, which on minikube is the admin client
# certificate - user `minikube-user` in group `system:masters`, which does not
# hold cluster-admin so much as SKIP RBAC. Every Secret in the cluster, every
# exec, every delete, `minikube`'s whole cluster, held permanently by a timer
# that lists five kinds of object and writes a JSON file. The rules below are
# the entirety of what that timer ever used.
#
# ── the grant, rule by rule, and the read that declared it ─────────────────
#
{table}
#
# ── why a ClusterRole, when bothy-kube deliberately has none ───────────────
#
# Because the collector's subject is the SET of namespaces, which is discovered
# and not declared. `kubectl get deployments --all-namespaces` is one
# cluster-scoped LIST, not a loop of namespaced ones, so a Role cannot authorise
# it however many namespaces it exists in; and the namespaces it would have to
# exist in are exactly the ones nobody has created yet. bothy-kube is the
# opposite case - two named namespaces, fixed in guard.NAMESPACES - so it gets
# Roles and this gets a ClusterRole, and each is the narrowest thing that works.
#
# The cost, stated rather than hidden: this account can enumerate the four
# namespaced kinds below in kube-system too. collect.py drops those client-side
# (K8S_SKIP_NS); RBAC has no way to express "every namespace except", and
# inventing one out of a hand-written namespace list would replace a discovered
# portal with a maintained one.
#
# ── what is NOT here, on purpose (load_reads refuses to generate it) ───────
#
#   get                      not granted, so not even one named object. `kubectl
#                            get <plural>` with no name is a LIST; nothing here
#                            ever fetches by name, so `get` would be a verb
#                            granted for a call that does not exist.
#   watch                    a 30-second timer does not need a stream, and an
#                            open watch is a connection the apiserver holds for
#                            an account that should be asleep between runs.
#   secrets, configmaps      credentials and config. Neither is read by collect.py.
#   pods, pods/log           the collector reports DEPLOYMENTS; pod bodies and
#                            their logs are Headlamp's job (bothy-browse) and
#                            bothy-ops', each with its own account.
#   pods/exec, attach, portforward, and every write verb - create, update,
#   patch, delete, deletecollection, escalate, bind, impersonate, `*`
#
# ── one ServiceAccount per consumer, and why not just reuse `view` ─────────
#
# bothy-browse (Headlamp) is already bound to the built-in `view` ClusterRole
# cluster-wide, and reusing it here would have been one line. `view` grants
# get/list/watch on some sixty kinds - pods, pod logs, configmaps, PVCs,
# serviceaccounts, events - where this needs list on five, and a shared account
# means revoking one consumer revokes the other. Separate accounts also make the
# audit log say WHICH thing read the cluster.
apiVersion: v1
kind: Namespace
metadata:
  name: bothy
  labels:
    app.kubernetes.io/part-of: bothy
    pod-security.kubernetes.io/enforce: restricted
    pod-security.kubernetes.io/enforce-version: latest
    pod-security.kubernetes.io/audit: restricted
    pod-security.kubernetes.io/warn: restricted
---
apiVersion: v1
kind: ServiceAccount
metadata:
  name: bothy-collector
  namespace: bothy
  labels:
    app.kubernetes.io/part-of: bothy
    app.kubernetes.io/name: bothy-collector
# The token is a Secret created by scripts/gen-collector-token.sh, never mounted
# into a pod - nothing runs as this account inside the cluster. It is used from
# OUTSIDE, by the host timer bothy-collector.service.
automountServiceAccountToken: false
---
apiVersion: rbac.authorization.k8s.io/v1
kind: ClusterRole
metadata:
  name: bothy-collector
  labels:
    app.kubernetes.io/part-of: bothy
    app.kubernetes.io/name: bothy-collector
rules:
"""

COLL_RBAC_TAIL = """\
---
apiVersion: rbac.authorization.k8s.io/v1
kind: ClusterRoleBinding
metadata:
  name: bothy-collector
  labels:
    app.kubernetes.io/part-of: bothy
    app.kubernetes.io/name: bothy-collector
roleRef:
  apiGroup: rbac.authorization.k8s.io
  kind: ClusterRole
  name: bothy-collector
subjects:
  - kind: ServiceAccount
    name: bothy-collector
    namespace: bothy
"""


def gen_collector_rbac(rows: list[dict[str, str]]) -> str:
    width = max(len(r["resource"]) for r in rows) + 2
    table = []
    for r in rows:
        table.append(f"#   {r['resource'].ljust(width)}list")
        table.append(f"#   {' ' * width}<- {r['id']}: {r['why']}")
    out = [COLL_RBAC_HEAD.format(stamp=COLL_STAMP, table="\n".join(table))]
    for r in rows:
        out.append(f"  - apiGroups: [{_q(r['group'])}]\n"
                   f"    resources: [{_q(r['resource'])}]\n"
                   f"    verbs: [\"list\"]\n")
    out.append(COLL_RBAC_TAIL)
    return "".join(out)


# Every one of these must answer `no`. They are asked of the apiserver, not of
# this file. Scope is a namespace, `-A` for every namespace, or `-` for cluster
# scope. `thales-pre-prod` is a namespace the collector genuinely reports on and
# `kube-system` one it throws away, so both are worth asking about.
COLL_MUST_NOT = [
    # the reads that are credentials, in every scope that exists
    ("list", "secrets", "-A"),
    ("get", "secrets", "thales-pre-prod"),
    ("get", "secrets", "bothy"),
    ("list", "configmaps", "-A"),
    # list is granted, get is not - one named object is a different request
    ("get", "deployments.apps", "thales-pre-prod"),
    ("get", "namespaces", "-"),
    ("watch", "deployments.apps", "-A"),
    # the kinds the collector does not read at all
    ("list", "pods", "-A"),
    ("get", "pods/log", "thales-pre-prod"),
    ("list", "nodes", "-"),
    ("list", "persistentvolumeclaims", "-A"),
    ("list", "events", "-A"),
    ("list", "serviceaccounts", "-A"),
    ("list", "roles.rbac.authorization.k8s.io", "-A"),
    ("list", "clusterroles.rbac.authorization.k8s.io", "-"),
    # a shell, a tunnel, a token
    ("create", "pods/exec", "thales-pre-prod"),
    ("get", "pods/exec", "thales-pre-prod"),
    ("create", "pods/attach", "thales-pre-prod"),
    ("create", "pods/portforward", "thales-pre-prod"),
    ("create", "serviceaccounts/token", "bothy"),
    ("impersonate", "serviceaccounts", "bothy"),
    ("escalate", "clusterroles.rbac.authorization.k8s.io", "-"),
    ("bind", "clusterroles.rbac.authorization.k8s.io", "-"),
    # every write, in a namespace it reports on and in kube-system
    ("create", "deployments.apps", "thales-pre-prod"),
    ("update", "deployments.apps", "thales-pre-prod"),
    ("patch", "deployments.apps", "thales-pre-prod"),
    ("delete", "deployments.apps", "thales-pre-prod"),
    ("patch", "deployments.apps", "kube-system"),
    ("delete", "pods", "kube-system"),
    ("create", "jobs.batch", "kube-system"),
    ("deletecollection", "pods", "-A"),
    ("create", "namespaces", "-"),
    ("delete", "namespaces", "-"),
]


def gen_collector_probes(rows: list[dict[str, str]]) -> str:
    out = ["# shellcheck shell=bash",
           f"# {COLL_STAMP}",
           "#",
           "# Sourced by scripts/gen-collector-token.sh, which defines",
           "#   probe <expect yes|no> <verb> <resource[/subresource]> <namespace | -A | - >",
           "# A subresource is written `pods/exec` here and goes to can-i as",
           "# --subresource=exec: `can-i get pods/exec` reads TYPE/NAME, so it asks about a",
           "# pod NAMED exec and answers for `get pods` (found 2026-09-17 in the other two",
           "# scripts, where it printed yes for a grant that did not exist).",
           "#",
           "# Every read reads.toml declares must be yes; every refusal must be no.",
           "",
           "# ── granted: list, and only list ──"]
    for r in rows:
        scope = "-" if r["scope"] == "cluster" else "-A"
        out.append(f"probe yes list {_can_i_target(r)} {scope}")
    out.append("# ── refused ──")
    for verb, res, scope in COLL_MUST_NOT:
        out.append(f"probe no {verb} {res} {scope}")
    return "\n".join(out) + "\n"


