#!/usr/bin/env python3
"""Generate the v1 control-plane wiring from operations.toml.   `just ops-v1`

    python3 scripts/gen-ops-v1.py            write apps/bothy-ops/generated/*
    python3 scripts/gen-ops-v1.py --check    exit 1 (with a diff) if any is stale  (T1; CI runs this)
    python3 scripts/gen-ops-v1.py --out DIR  write them under DIR instead

apps/bothy-ops/operations.toml is the ONE hand-written description of the control plane's
operations (docs/plans/thin-bothy/cli-and-control-plane.md, 1.2). Everything else is an output:

  edge-routers.v1.yml   one exact Path() router per op that lists "session" or "token" in its
                        `exposure` (D42; the default is ["socket"], which needs no router),
                        sso-<role> gated for "session", no Host(). May be comment-only. INERT:
                        it lives in apps/bothy-ops/generated/, NOT edge/dynamic/, so Traefik does
                        not load it and the router counts the docs state do not move. Installing
                        it (copy to edge/dynamic/bothy-ops-v1.yml, then `just ops-v1` + the
                        router-gates count docs) is the slice that exposes the API at the edge.
  openapi.v1.json       an OpenAPI 3.1 document (paths, parameters, response schemas; untrusted
                        strings carry `x-bothy-trust`)
  mcp-tools.v1.json     the MCP tool list: name, description, JSON-Schema input, readOnlyHint
  cli-verbs.v1.json     the CLI's verb table: verb words, op id, method, path, params

The Go client is generated or checked against these; the Python never hand-copies them.
"""
import difflib
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OPS = os.path.join(ROOT, "apps", "bothy-ops")
OUT = os.path.join(OPS, "generated")
sys.path.insert(0, OPS)
import caller  # noqa: E402
import opscatalog  # noqa: E402


def entries(cat: dict) -> list[dict]:
    """Every routed endpoint, discover first, then the ops in file order."""
    return [cat["endpoints"]["discover"], *cat["ops"].values()]


def route_of(e: dict) -> str:
    return e["http"].split(" ", 1)[1]


def json_schema(s: dict) -> dict:
    """The catalog's schema dialect -> JSON Schema. `untrusted` is a string wrapped in an object."""
    t = s.get("type")
    if t == "untrusted":
        out = {"type": "object", "required": ["text", "trust", "source"],
               "properties": {"text": {"type": "string"}, "trust": {"const": "untrusted"},
                              "source": {"const": s["source"]}},
               "x-bothy-trust": "untrusted"}
        return {"anyOf": [out, {"type": "null"}]} if s.get("nullable") else out
    out: dict = {}
    if t:
        out["type"] = [t, "null"] if s.get("nullable") else t
    for k in ("enum", "pattern", "minimum", "maximum"):
        if k in s:
            out[k] = s[k]
    if "required" in s:
        out["required"] = list(s["required"])
    if "properties" in s:
        out["properties"] = {k: json_schema(v) for k, v in s["properties"].items()}
    if "items" in s:
        out["items"] = json_schema(s["items"])
    return out


def params(e: dict) -> list[dict]:
    ps = []
    for name, spec in e.get("input", {}).items():
        sch = {"type": spec["type"]}
        if "pattern" in spec:
            sch["pattern"] = "^" + spec["pattern"] + "$"
        if "enum" in spec:
            sch["enum"] = spec["enum"]
        if "min" in spec:
            sch["minimum"] = spec["min"]
        if "max" in spec:
            sch["maximum"] = spec["max"]
        if "default" in spec:
            sch["default"] = spec["default"]
        p = {"name": name, "in": "query", "required": bool(spec.get("required")), "schema": sch}
        if "one_of" in spec:
            p["x-bothy-one-of"] = spec["one_of"]
        ps.append(p)
    return ps


ERRORS = {"auth.unauthenticated": 401, "auth.forbidden": 403, "request.invalid": 400,
          "request.not-found": 404, "unavailable.source": 503, "internal.error": 500}


def edge_exposed(e: dict) -> bool:
    return any(x in caller.EDGE_EXPOSURES for x in e["exposure"])


def render_routers(cat: dict) -> str:
    L = ["# GENERATED by scripts/gen-ops-v1.py from apps/bothy-ops/operations.toml - DO NOT EDIT. Run `just ops-v1`.",
         "#",
         "# INERT. This file is NOT in edge/dynamic/, so Traefik does not read it. To expose the v1 API at the",
         "# edge, copy it to edge/dynamic/bothy-ops-v1.yml and update the router counts the docs state",
         "# (scripts/checks/router-gates.sh names them). Exact Path() only, never a host rule, never a prefix:",
         "# a new op is unreachable until its router exists. Gates are borrowed from edge/dynamic/bothy-gates.yml.",
         "# No doubled curly braces anywhere in this file (it is rendered as a Go template).",
         "# Only an op whose `exposure` lists \"session\" or \"token\" gets a router; a socket-only op (the",
         "# default) is reached on the local socket and is deliberately not routed here."]
    routed = [e for e in entries(cat) if edge_exposed(e)]
    if routed:
        L += ["http:", "  routers:"]
    for e in routed:
        slug = e["id"].replace(".", "-")
        # "session": the cookie gate for the op's role. "token" only: no cookie gate (it would refuse a
        # bearer token); bothy-ops verifies the token itself (slice 2) and refuses until then.
        gate = [f"sso-{e['role']}"] if "session" in e["exposure"] else []
        # A token route also carries v1-client-address (edge/dynamic/bothy-v1-client.yml): the limiter's key.
        client = ["v1-client-address"] if "token" in e["exposure"] else []
        L += [f"    bothy-ops-v1-{slug}:",
              f"      rule: \"Path(`{route_of(e)}`)\"",
              "      entryPoints: [web]",
              "      priority: 110",
              "      service: bothy-ops",
              f"      middlewares: [{', '.join(['bothy-ops-strip', *client, 'ops-deidentify', *gate, 'sso-errors'])}]", ""]
    return "\n".join(L).rstrip("\n") + "\n"


def render_openapi(cat: dict) -> str:
    api = cat["api"]
    env_err = {"type": "object", "required": ["ok", "request_id", "error"],
               "properties": {"ok": {"const": False}, "request_id": {"type": "string"},
                              "error": {"type": "object", "required": ["code", "message", "details", "hint"],
                                        "properties": {"code": {"type": "string", "enum": sorted(ERRORS)},
                                                       "message": {"type": "string"}, "details": {"type": "object"},
                                                       "hint": {"type": ["string", "null"]}}}}}
    paths = {}
    for e in entries(cat):
        ok = {"type": "object", "required": ["ok", "request_id", "data", "warnings"],
              "properties": {"ok": {"const": True}, "request_id": {"type": "string"},
                             "data": json_schema(e["output"]),
                             "warnings": {"type": "array", "items": {"type": "string"}}}}
        paths[route_of(e)] = {"get": {
            "operationId": e["id"], "summary": e["title"], "parameters": params(e),
            "x-bothy": {"role": e["role"], "exposure": e["exposure"], "effect": e["effect"], "confirm": e["confirm"],
                        "audit": e["audit"], "callers": e["callers"], "idempotent": e["idempotent"]},
            "responses": {"200": {"description": "ok", "content": {"application/json": {"schema": ok}}},
                          **{str(c): {"description": code, "content": {"application/json": {
                              "schema": {"$ref": "#/components/schemas/Error"}}}}
                             for code, c in sorted(ERRORS.items(), key=lambda kv: kv[1]) if c not in (401,)}}}}
    doc = {"openapi": "3.1.0",
           "info": {"title": "Bothy control plane", "version": str(api["version"]),
                    "x-min-client": api["min_client"]},
           "paths": paths, "components": {"schemas": {"Error": env_err}}}
    return json.dumps(doc, indent=2, sort_keys=True) + "\n"


def render_mcp(cat: dict) -> str:
    tools = []
    for o in cat["ops"].values():
        m = o.get("mcp")
        if not m:
            continue
        props, req = {}, []
        for p in params(o):
            props[p["name"]] = p["schema"]
            if p["required"]:
                req.append(p["name"])
        tools.append({"name": m["tool"], "description": o["title"], "operation": o["id"],
                      "inputSchema": {"type": "object", "properties": props, "required": req,
                                      "additionalProperties": False},
                      "annotations": {"readOnlyHint": o["effect"] == "read", "idempotentHint": o["idempotent"],
                                      "destructiveHint": o["effect"] in ("destructive", "loosen")},
                      "scope": m["scope"]})
    return json.dumps({"api_version": cat["api"]["version"], "tools": tools}, indent=2, sort_keys=True) + "\n"


def render_cli(cat: dict) -> str:
    verbs = [{"verb": e["cli"].split(), "operation": e["id"], "method": "GET", "path": route_of(e),
              "params": params(e), "role": e["role"]} for e in entries(cat) if e.get("cli")]
    return json.dumps({"api_version": cat["api"]["version"], "verbs": verbs}, indent=2, sort_keys=True) + "\n"


def render_all(cat: dict) -> dict[str, str]:
    return {"edge-routers.v1.yml": render_routers(cat), "openapi.v1.json": render_openapi(cat),
            "mcp-tools.v1.json": render_mcp(cat), "cli-verbs.v1.json": render_cli(cat)}


def main(argv: list[str]) -> int:
    out = OUT
    if "--out" in argv:
        out = argv[argv.index("--out") + 1]
    try:
        files = render_all(opscatalog.load())
    except opscatalog.CatalogError as e:
        print(f"gen-ops-v1: operations.toml does not load: {e}", file=sys.stderr)
        return 2
    for name, text in files.items():
        if "{{" in text:
            print(f"gen-ops-v1: {name} contains a doubled curly brace (Go template trap)", file=sys.stderr)
            return 2
    if "--check" in argv:
        bad = 0
        for name, text in files.items():
            p = os.path.join(out, name)
            have = open(p, encoding="utf-8").read() if os.path.exists(p) else ""
            if have != text:
                bad += 1
                sys.stdout.writelines(difflib.unified_diff(have.splitlines(True), text.splitlines(True),
                                                           f"{name} (committed)", f"{name} (generated)", n=2))
        if bad:
            print(f"\ngen-ops-v1: {bad} generated file(s) stale - run `just ops-v1`", file=sys.stderr)
            return 1
        print(f"gen-ops-v1: {len(files)} generated files match operations.toml")
        return 0
    os.makedirs(out, exist_ok=True)
    for name, text in files.items():
        with open(os.path.join(out, name), "w", encoding="utf-8") as fh:
            fh.write(text)
    print(f"gen-ops-v1: wrote {len(files)} files to {out}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
