export type IconName = keyof typeof PATHS;

/** One glyph. Decorative (`aria-hidden`): the words next to it carry the meaning. */
export function icon(name: IconName, size: IconSize = 'md', cls = '', strokeWidth = 1.25): string {
  const body = PATHS[name];
  const px = ICON[size];
  // absoluteStrokeWidth: the stroke is in px at the rendered size, so it is scaled back to the 24-unit box.
  const stroke = +((strokeWidth * 24) / px).toFixed(3);
  const c = cls ? ` class="${cls}"` : '';
  return `<svg${c} xmlns="http://www.w3.org/2000/svg" width="${px}" height="${px}" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="${stroke}" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true">${body}</svg>`;
}
