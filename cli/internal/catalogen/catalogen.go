// Package catalogen renders ops_gen.go from the two catalog JSON files. It is
// a package (not just a main) so a test can re-render in memory and compare
// with the committed file: that is the drift check, and it needs no git.
package catalogen

import (
	"bytes"
	"crypto/sha256"
	"encoding/json"
	"fmt"
	"go/format"
	"sort"
	"strings"
)

type verbsFile struct {
	APIVersion int `json:"api_version"`
	Verbs      []struct {
		Method    string   `json:"method"`
		Operation string   `json:"operation"`
		Path      string   `json:"path"`
		Role      string   `json:"role"`
		Verb      []string `json:"verb"`
		Params    []struct {
			In       string `json:"in"`
			Name     string `json:"name"`
			Required bool   `json:"required"`
			OneOf    string `json:"x-bothy-one-of"`
			Schema   struct {
				Type    string   `json:"type"`
				Pattern string   `json:"pattern"`
				Enum    []string `json:"enum"`
				Default *int     `json:"default"`
				Min     *int     `json:"minimum"`
				Max     *int     `json:"maximum"`
			} `json:"schema"`
		} `json:"params"`
	} `json:"verbs"`
}

type toolsFile struct {
	APIVersion int `json:"api_version"`
	Tools      []struct {
		Name        string          `json:"name"`
		Operation   string          `json:"operation"`
		Scope       string          `json:"scope"`
		Description string          `json:"description"`
		InputSchema json.RawMessage `json:"inputSchema"`
	} `json:"tools"`
}

// Render returns the formatted Go source of ops_gen.go.
func Render(verbsJSON, toolsJSON []byte) ([]byte, error) {
	var vf verbsFile
	var tf toolsFile
	if err := json.Unmarshal(verbsJSON, &vf); err != nil {
		return nil, fmt.Errorf("cli-verbs: %w", err)
	}
	if err := json.Unmarshal(toolsJSON, &tf); err != nil {
		return nil, fmt.Errorf("mcp-tools: %w", err)
	}
	if vf.APIVersion != tf.APIVersion {
		return nil, fmt.Errorf("api_version differs: verbs %d, tools %d", vf.APIVersion, tf.APIVersion)
	}
	tools := map[string]int{}
	for i, t := range tf.Tools {
		tools[t.Operation] = i
	}
	seenVerb := map[string]bool{}
	var b bytes.Buffer
	sum := sha256.Sum256(append(append([]byte{}, verbsJSON...), toolsJSON...))
	fmt.Fprintf(&b, "// Code generated by cmd/catalogen from apps/bothy-ops/generated/{cli-verbs,mcp-tools}.v1.json; DO NOT EDIT.\n")
	fmt.Fprintf(&b, "// Input sha256: %x\n\npackage catalog\n\n", sum)
	fmt.Fprintf(&b, "// APIVersion is the API version this table was generated for.\nconst APIVersion = %d\n\n", vf.APIVersion)
	b.WriteString("// Ops is every operation the catalog declares, in catalog order.\nvar Ops = []Op{\n")
	used := map[string]bool{}
	for _, v := range vf.Verbs {
		vs := strings.Join(v.Verb, " ")
		if seenVerb[vs] {
			return nil, fmt.Errorf("duplicate verb %q", vs)
		}
		seenVerb[vs] = true
		fmt.Fprintf(&b, "\t{ID: %q, Method: %q, Path: %q, Role: %q, Verb: []string{", v.Operation, v.Method, v.Path, v.Role)
		for i, w := range v.Verb {
			if i > 0 {
				b.WriteString(", ")
			}
			fmt.Fprintf(&b, "%q", w)
		}
		b.WriteString("},\n")
		if len(v.Params) > 0 {
			b.WriteString("\t\tParams: []Param{\n")
			for _, p := range v.Params {
				if p.In != "query" {
					return nil, fmt.Errorf("%s.%s: only query params are supported, got %q", v.Operation, p.Name, p.In)
				}
				fmt.Fprintf(&b, "\t\t\t{Name: %q, Required: %v, Type: %q", p.Name, p.Required, p.Schema.Type)
				if p.Schema.Pattern != "" {
					fmt.Fprintf(&b, ", Pattern: %q", p.Schema.Pattern)
				}
				if len(p.Schema.Enum) > 0 {
					b.WriteString(", Enum: []string{")
					for i, e := range p.Schema.Enum {
						if i > 0 {
							b.WriteString(", ")
						}
						fmt.Fprintf(&b, "%q", e)
					}
					b.WriteString("}")
				}
				if p.Schema.Default != nil {
					fmt.Fprintf(&b, ", Default: %q", fmt.Sprint(*p.Schema.Default))
				}
				if p.Schema.Min != nil {
					fmt.Fprintf(&b, ", HasMin: true, Min: %d", *p.Schema.Min)
				}
				if p.Schema.Max != nil {
					fmt.Fprintf(&b, ", HasMax: true, Max: %d", *p.Schema.Max)
				}
				if p.OneOf != "" {
					fmt.Fprintf(&b, ", OneOf: %q", p.OneOf)
				}
				b.WriteString("},\n")
			}
			b.WriteString("\t\t},\n")
		}
		if i, ok := tools[v.Operation]; ok {
			t := tf.Tools[i]
			used[v.Operation] = true
			var compact bytes.Buffer
			if err := json.Compact(&compact, t.InputSchema); err != nil {
				return nil, fmt.Errorf("%s: inputSchema: %w", t.Name, err)
			}
			fmt.Fprintf(&b, "\t\tTool: %q, Scope: %q, Description: %q,\n\t\tInputSchema: %q,\n", t.Name, t.Scope, t.Description, compact.String())
		}
		b.WriteString("\t},\n")
	}
	b.WriteString("}\n")
	var orphan []string
	for op := range tools {
		if !used[op] {
			orphan = append(orphan, op)
		}
	}
	if len(orphan) > 0 {
		sort.Strings(orphan)
		return nil, fmt.Errorf("mcp-tools names operations missing from cli-verbs: %v", orphan)
	}
	return format.Source(b.Bytes())
}
